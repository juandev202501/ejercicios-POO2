    private void btnGuardarPCatedraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPCatedraActionPerformed

        try {
            String codigo = txCodigo.getText();
            String nombre = txtNombre.getText();
            String titulo = txtTituloAcademico.getText();
            String depto = txtDepartamento.getText();
            int salarioBasico = Integer.parseInt(txtSalarioBasico.getText());

            int numContrato = Integer.parseInt(txtNumeroDeContratoSemestral.getText());
            int horas = Integer.parseInt(txtNumeroDeHorasQueDictaPorSemana.getText());
            int valorHora = Integer.parseInt(txtValorHora.getText());

            

            this.areaInformacion.setText(myControlador.registrarDocenteCatedra(codigo, nombre, titulo, depto, salarioBasico, numContrato, horas, valorHora));
            limpiarCamposGenerales();
            limpiarCamposEspecificos();
            activarBotonesReporte();
        } catch (NumberFormatException e) {
            this.areaInformacion.setText("Por favor verifique los campos numéricos. Error de ingreso");
        }
    }//GEN-LAST:event_btnGuardarPCatedraActionPerformed

