    private void btnGuardadPPlantaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardadPPlantaActionPerformed

        try {
            String codigo = txCodigo.getText();
            String nombre = txtNombre.getText();
            String titulo = txtTituloAcademico.getText();
            String depto = txtDepartamento.getText();
            int salarioBasico = Integer.parseInt(txtSalarioBasico.getText());

            int puntos = Integer.parseInt(txtNumeroDePuntosSalariales.getText());
            int valorPunto = Integer.parseInt(txtValorDelPuntoSalarial.getText());
            String categoria = txtCategoria.getText();
            int numRes = Integer.parseInt(txtNumeroDeResolucionDeNombramiento.getText());

            java.util.Date date = (java.util.Date) spinnerFechaDeNombramiento.getValue();
            java.time.LocalDateTime fecha = date.toInstant()
                    .atZone(java.time.ZoneId.systemDefault())
                    .toLocalDateTime();

            

            this.areaInformacion.setText(myControlador.registrarDocentePlanta(codigo, nombre, titulo, depto, salarioBasico, puntos, valorPunto, categoria, numRes, fecha));
            limpiarCamposGenerales();
            limpiarCamposEspecificos();
            activarBotonesReporte();
        } catch (NumberFormatException e) {
            this.areaInformacion.setText("Por favor verifique los campos numéricos. Error de ingreso");
        }

    }//GEN-LAST:event_btnGuardadPPlantaActionPerformed

