    public void mostrarEnBandej(String mensaje) {
    DateTimeFormatter formato = DateTimeFormatter.ofPattern("HH:mm-dd/MM/yyyy");
    this.txaBandejaEntrada.append("[" + LocalDateTime.now().format(formato) + "] " + mensaje + "\n" + "\n");
}

